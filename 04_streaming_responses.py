"""
================================================================================
Module 04: Streaming Responses in Real Time (Google Gemini Edition)
================================================================================

CONCEPT OVERVIEW:
-----------------
When generating long responses, waiting for the entire generation to finish can
cause a frustrating delay (often several seconds of blank screen).

"Streaming" allows the client to receive tokens piece-by-piece as they are
generated by the model on Google's servers.

WHY THIS PATTERN MATTERS:
-------------------------
1. User Experience (UX): Drastically reduces perceived latency (Time-to-First-Token,
   or TTFT). The user starts reading words within a fraction of a second.
2. Responsiveness: Ideal for conversational chat interfaces, live CLI assistants,
   and interactive applications.

GEMINI SPECIFICS:
-----------------
Under the hood, `model.stream()` uses HTTP Server-Sent Events (SSE) or streaming
gRPC to receive token deltas. Each iteration yields an `AIMessageChunk`.
LangChain's chunk object includes:
- `chunk.content` (or `chunk.text`) containing the newly generated token delta.
================================================================================
"""

import os
import sys
import time
from dotenv import load_dotenv

# ------------------------------------------------------------------------------
# 1. Environment & Setup
# ------------------------------------------------------------------------------
load_dotenv()

gemini_key = os.getenv("GEMINI_API_KEY")
if gemini_key and not os.getenv("GOOGLE_API_KEY"):
    os.environ["GOOGLE_API_KEY"] = gemini_key

from langchain.chat_models import init_chat_model

# We can specify STREAM_MODEL or default to GEMINI_MODEL
MODEL_NAME = os.getenv("STREAM_MODEL", os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite"))
print(f"[Streaming Setup] Initializing model '{MODEL_NAME}' for streaming output...\n")

model = init_chat_model(MODEL_NAME, model_provider="google_genai", temperature=0.3)


# ------------------------------------------------------------------------------
# 2. Executing the Stream
# ------------------------------------------------------------------------------
def main():
    prompt = "Explain Python in 500 words, highlighting why AI seems to have adopted it as default."
    print(f"--- Prompt: '{prompt}' ---")
    print("--- Streaming Tokens (Watch text appear in real-time) ---\n")

    start_time = time.perf_counter()
    first_token_time = None
    token_count = 0

    # `model.stream()` returns an iterator yielding `AIMessageChunk` objects
    for chunk in model.stream(prompt):
        if first_token_time is None:
            first_token_time = time.perf_counter()

        # Retrieve the text piece from the chunk
        # In modern LangChain, chunk.text extracts clean text even across complex parts
        text_piece = getattr(chunk, "text", "")
        if not text_piece and isinstance(chunk.content, str):
            text_piece = chunk.content
        elif not text_piece and isinstance(chunk.content, list):
            # If chunk.content is a list of parts
            text_piece = "".join(
                part.get("text", "") for part in chunk.content if isinstance(part, dict)
            )

        if text_piece:
            token_count += 1
            # Print without newline and flush stdout immediately so output renders live
            sys.stdout.write(text_piece)
            sys.stdout.flush()

    total_time = time.perf_counter() - start_time
    ttft = (first_token_time - start_time) if first_token_time else total_time

    print("\n\n-------------------------------------------------------------")
    print(f"Streaming Complete!")
    print(f"Time to First Token (TTFT): {ttft:.2f} seconds")
    print(f"Total Stream Duration:       {total_time:.2f} seconds")
    print("-------------------------------------------------------------")


if __name__ == "__main__":
    main()
