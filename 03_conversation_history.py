"""
================================================================================
Module 03: Managing Conversation History & Message Roles (Google Gemini)
================================================================================

CONCEPT OVERVIEW:
-----------------
Large Language Models (LLMs) are completely STATELESS. The model does not
remember what you said two seconds ago unless you send the prior conversation
back to the model with every new request.

To represent a multi-turn conversation, LangChain standardizes messages into
three primary classes:
1. `SystemMessage`: High-level instructions, personality, tone, and constraints.
   (In Google Gemini, this maps directly to `system_instruction`).
2. `HumanMessage`: Queries, inputs, and instructions originating from the user.
3. `AIMessage`: Prior responses generated by the assistant/model.

WHY THIS PATTERN MATTERS:
-------------------------
By passing a structured list of `[SystemMessage, HumanMessage, AIMessage, ...]`,
the model has complete contextual awareness. It can resolve pronouns (e.g.,
"When was it released?" referring to "Python" from the previous turn) and follow
complex multi-step reasoning.

GEMINI SPECIFICS:
-----------------
The Gemini API maps:
- `SystemMessage` -> `system_instruction`
- `HumanMessage`  -> `Content(role='user', parts=[...])`
- `AIMessage`    -> `Content(role='model', parts=[...])`
LangChain handles this transformation automatically, ensuring cross-provider
portability.
================================================================================
"""

import os
from dotenv import load_dotenv

# ------------------------------------------------------------------------------
# 1. Environment & Setup
# ------------------------------------------------------------------------------
load_dotenv()

gemini_key = os.getenv("GEMINI_API_KEY")
if gemini_key and not os.getenv("GOOGLE_API_KEY"):
    os.environ["GOOGLE_API_KEY"] = gemini_key

from langchain.chat_models import init_chat_model
from langchain_core.messages import AIMessage, HumanMessage, SystemMessage

MODEL_NAME = os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite")
model = init_chat_model(MODEL_NAME, model_provider="google_genai", temperature=0.1)


# ------------------------------------------------------------------------------
# 2. Assembling Multi-Turn Conversation History
# ------------------------------------------------------------------------------
def main():
    print("--- Simulating a Multi-Turn Conversation with Context Retention ---")

    # We manually construct a conversation history list.
    # Notice the flow:
    # Turn 1: User asks "What is Python?"
    # Turn 2: AI answers "Python is a high-level programming language..."
    # Turn 3: User asks "When was it first released, and who created it?"
    #
    # Without the history, the model wouldn't know what "it" refers to!
    conversation = [
        SystemMessage(
            content="You are a knowledgeable computer science historian. Provide concise, factual answers."
        ),
        HumanMessage(
            content="What is Python?"
        ),
        AIMessage(
            content="Python is a high-level, interpreted programming language known for its readability and versatile standard library."
        ),
        HumanMessage(
            content="When was it first released, and who created it?"
        ),
    ]

    print(f"Total Messages in Context: {len(conversation)}")
    for i, msg in enumerate(conversation, 1):
        print(f"  {i}. [{msg.__class__.__name__}]: {msg.content}")

    # --------------------------------------------------------------------------
    # 3. Invoking the Model with History
    # --------------------------------------------------------------------------
    print("\n--- Invoking Gemini with Full Conversation Context ---")
    response = model.invoke(conversation)

    answer = getattr(response, "text", response.content)
    print("\n--- Model Response ---")
    print(answer)

    # --------------------------------------------------------------------------
    # 4. Appending the New Response to Continue the Chat
    # --------------------------------------------------------------------------
    # In an ongoing application (like a web chat or terminal assistant), you
    # simply append the new AIMessage to the list:
    conversation.append(response)
    conversation.append(HumanMessage(content="What was the major controversy with version 3.0?"))

    print("\n--- Follow-up Turn ---")
    followup_response = model.invoke(conversation)
    followup_text = getattr(followup_response, "text", followup_response.content)
    print(followup_text)


if __name__ == "__main__":
    main()
